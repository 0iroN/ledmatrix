# Türkçe harfler = temel harf + üst işaret (gövdenin 1 satır üstü, araya 1 boş satır)
# ve/veya alt işaret (gövdenin hemen altı, çengel gövdeye yapışık).
# 16 px yükseklikte 7'lik gövdenin üstünde 4, altında 5 satır boş — sığıyorlar.
TR = {
    "Ç": ("C", [], ["..#..", ".#..."]),
    "Ş": ("S", [], ["..#..", ".#..."]),
    "Ğ": ("G", ["#...#", ".###."], []),
    "Ö": ("O", [".#.#."], []),
    "Ü": ("U", [".#.#."], []),
    "İ": ("I", ["..#.."], []),
}


def tr_upper(text: str) -> str:
    """Türkçe büyük harf: i -> İ, ı -> I (Python'un upper()'ı i'yi I yapar)."""
    return text.replace("i", "İ").replace("ı", "I").upper()


def text_width(text: str) -> int:
    return max(len(text) * (W + 1) - 1, 0)


def render(text: str, rgb=(255, 140, 0), height: int = 16) -> Image.Image:
    """Yazıyı dikeyde ortalanmış tek satır olarak çizer; genişlik = yazının boyu."""
    text = tr_upper(text)
    img = Image.new("RGB", (max(text_width(text), 1), height))
    top = (height - H) // 2

    def ciz(satirlar, x0, y0):
        for gy, row in enumerate(satirlar):
            for gx, c in enumerate(row):
                if c == "#" and 0 <= y0 + gy < height:
                    img.putpixel((x0 + gx, y0 + gy), rgb)

    for n, ch in enumerate(text):
        x0 = n * (W + 1)
        if ch in TR:
            temel, ust, alt = TR[ch]
            ciz(GLYPHS[temel], x0, top)
            ciz(ust, x0, top - 1 - len(ust))
            ciz(alt, x0, top + H)
        else:
            ciz(GLYPHS.get(ch, GLYPHS["?"]), x0, top)
    return img
